// Writes src/game/skin-card-faces.ts: which cards each skin has pre-composited faces
// and illustrations for, read from public/assets/skin-cards*, skin-card-art. The
// client resolves a skin's card image only for keys listed there, so a card a skin
// does not cover keeps its default look instead of requesting a missing file.
//
//   node scripts/sync-skin-card-faces.mjs          # rewrite the module
//   node scripts/sync-skin-card-faces.mjs --check  # fail if it is stale
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const assets = join(repoRoot, 'public/assets')
const target = join(repoRoot, 'src/game/skin-card-faces.ts')

const names = (dir, suffix) => existsSync(dir)
  ? readdirSync(dir).filter((file) => file.endsWith(suffix)).map((file) => file.slice(0, -suffix.length)).sort()
  : []

export function skinCardFaces() {
  const skins = existsSync(join(assets, 'skin-cards')) ? readdirSync(join(assets, 'skin-cards')).sort() : []
  return Object.fromEntries(skins.map((skin) => {
    const artRoot = join(assets, 'skin-card-art', skin)
    const art = existsSync(artRoot)
      ? readdirSync(artRoot).sort().flatMap((owner) => names(join(artRoot, owner), '.webp').map((id) => `${owner}/${id}`))
      : []
    return [skin, { faces: names(join(assets, 'skin-cards', skin), '.webp'), art }]
  }))
}

const render = (faces) => `// Generated by scripts/sync-skin-card-faces.mjs from public/assets/skin-cards*, skin-card-art. Do not edit.
// \`faces\` are card asset keys (see cardAssetKey in assets.ts); \`art\` is \`<owner>/<cardId>\`.
export const SKIN_CARD_FACES: Readonly<Record<string, { readonly faces: readonly string[]; readonly art: readonly string[] }>> = ${
  JSON.stringify(faces, null, 2)}
`

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = render(skinCardFaces())
  if (process.argv.includes('--check')) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== next) {
      console.error('src/game/skin-card-faces.ts is stale; run node scripts/sync-skin-card-faces.mjs')
      process.exit(1)
    }
  } else writeFileSync(target, next)
}
